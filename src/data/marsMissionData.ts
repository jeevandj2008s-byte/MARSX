function createTarget(
  raw: Omit<ScienceTarget, 'coords'> & { lat: number; lon: number }
): ScienceTarget {
  const { lat, lon, ...rest } = raw;
  return {
    ...rest,
    coords: sampleJezeroCraterTerrain(lat, lon),
  };
}

